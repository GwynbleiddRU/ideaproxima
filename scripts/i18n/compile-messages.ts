import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { compileMessageCatalogues } from "./message-catalogues";

const destination = new URL("../../packages/i18n/src/compiled-messages.ts", import.meta.url);
const compiled = JSON.stringify(compileMessageCatalogues());
const source = `// Generated by npm run i18n:compile. Keep source messages in their catalogues.
import type { Messages } from "@lingui/core";
import type { Locale } from "./locales";

export const COMPILED_MESSAGES = ${compiled} satisfies Partial<Record<Locale, Messages>>;
`;
const config = await resolveConfig(fileURLToPath(destination));
writeFileSync(destination, await format(source, { ...config, parser: "typescript" }));
