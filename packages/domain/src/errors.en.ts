export type ErrorReason = keyof typeof ERROR_MESSAGES;
export type ErrorParams = Readonly<Record<string, string | number>>;

/** Domain errors carry English messages even in scripts and workers without a translator. */
export function englishErrorMessage(reason: ErrorReason, params: ErrorParams): string {
  return ERROR_MESSAGES[reason].replace(/\{(\w+)\}/g, (placeholder, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : placeholder,
  );
}
